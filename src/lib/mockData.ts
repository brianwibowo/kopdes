export function getNationalStats(): NationalStats {
  const totalKoperasi = MOCK_KOPERASI.length;
  let totalAnggota = 0;
  let totalAset = 0;
  let totalVolumeUsaha = 0;
  let koperasiAktif = 0;
  let koperasiPerluAtensi = 0;

  const tahapCounts = {
    tahap1: 0,
    tahap2: 0,
    tahap3: 0,
    tahap4: 0,
  };

  const provMap: Record<string, number> = {};

  for (const k of MOCK_KOPERASI) {
    totalAnggota += k.jumlahAnggota;
    totalAset += k.totalAset;
    totalVolumeUsaha += k.volumeUsaha;

    if (k.status === "AKTIF") koperasiAktif++;
    if (k.status === "PERLU_ATENSI") koperasiPerluAtensi++;

    if (k.tahap === "TAHAP_1_PERSIAPAN") tahapCounts.tahap1++;
    if (k.tahap === "TAHAP_2_KELEMBAGAAN") tahapCounts.tahap2++;
    if (k.tahap === "TAHAP_3_PERMODALAN") tahapCounts.tahap3++;
    if (k.tahap === "TAHAP_4_OPERASIONAL") tahapCounts.tahap4++;

    provMap[k.provinsiNama] = (provMap[k.provinsiNama] || 0) + 1;
  }

  const provinsiTerbanyak = Object.entries(provMap)
    .map(([nama, jumlah]) => ({ nama, jumlah }))
    .sort((a, b) => b.jumlah - a.jumlah)
    .slice(0, 5);

  return {
    totalKoperasi,
    totalAnggota,
    totalAset,
    totalVolumeUsaha,
    koperasiAktif,
    koperasiPerluAtensi,
    tahapCounts,
    provinsiTerbanyak,
  };
}
